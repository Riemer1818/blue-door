#!/usr/bin/env node
/**
 * Generate TypeScript types from `tools/outcomes.json`.
 *
 * The vocabulary is stated once, in that file, and read twice: `events.py`
 * asserts at import that every tool outcome has an action, and this emits the
 * types that let the compiler check the same thing on the frontend.
 *
 * Restating the outcomes in TypeScript by hand would buy a compile-time check at
 * the cost of two statements of one vocabulary drifting apart — the same trap as
 * the alphabet rule, and a compile error about a stale copy is worse than a
 * runtime assertion about the real thing. Generating gets both.
 *
 * THE ACTION UNION IS BUILT FROM `actions.order` ALONE, deliberately. If an
 * outcome names an action that nothing renders, the generated `Record` fails to
 * typecheck rather than producing an outcome that quietly appears in no group.
 * That is the mirror of the assertion on the Python side: theirs catches an
 * outcome with no action, this catches an action with no group. Same silence,
 * opposite direction.
 *
 * Run by `pnpm outcomes:types`, and by `pnpm typecheck` before tsc, so a stale
 * generated file cannot survive a check.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const TOOLS_DIR = process.env.TOOLS_DIR ?? path.join(process.cwd(), "..", "tools");
const OUT = path.join(process.cwd(), "src", "lib", "outcomes.generated.ts");

const quote = (value) => JSON.stringify(value);
const union = (values) => values.map(quote).join(" | ");

const raw = JSON.parse(await readFile(path.join(TOOLS_DIR, "outcomes.json"), "utf8"));

const toolOutcomes = Object.entries(raw.tool_outcomes);
const agentOutcomes = Object.keys(raw.agent_outcomes);
const actions = raw.actions.order;

const file = `// GENERATED by scripts/generate-outcomes.mjs from tools/outcomes.json.
// Do not edit. Run \`pnpm outcomes:types\` after changing that file.
//
// Vocabulary version ${quote(raw.version)}.

/** What a run of a wrapped tool ended as. */
export type ToolOutcome = ${union(toolOutcomes.map(([name]) => name))};

/** What a run of the adapter agent ended as. None of these means "ready". */
export type AgentOutcome = ${union(agentOutcomes)};

/**
 * What a person does next. Outcomes are grouped by this rather than by what went
 * wrong: \`precondition_failed\` and \`oom\` are both "no result", but one is fixed
 * by choosing a different file and the other by us, and telling someone to wait
 * when they are one dropdown from done is worse than not grouping at all.
 */
export type OutcomeAction = ${union(actions)};

/** Rendering order. A list, not a set — "we fix it" must not sort above "choose a different file". */
export const ACTION_ORDER: readonly OutcomeAction[] = [
${actions.map((a) => `  ${quote(a)},`).join("\n")}
];

/**
 * Every tool outcome with its description and action.
 *
 * Typed as a total \`Record\`, so an outcome added to outcomes.json without being
 * handled here fails to compile — and an outcome whose action is not in
 * ACTION_ORDER fails too, because OutcomeAction is built from that list alone.
 */
export const TOOL_OUTCOMES: Record<ToolOutcome, { description: string; action: OutcomeAction }> = {
${toolOutcomes
  .map(
    ([name, spec]) =>
      `  ${quote(name)}: { description: ${quote(spec.description)}, action: ${quote(spec.action)} },`,
  )
  .join("\n")}
};

export const AGENT_OUTCOMES: Record<AgentOutcome, { description: string }> = {
${agentOutcomes
  .map((name) => `  ${quote(name)}: { description: ${quote(raw.agent_outcomes[name].description)} },`)
  .join("\n")}
};

/**
 * Numbers a \`timeout\` carries, because it is the one outcome whose correct
 * action genuinely depends on the run. "180s budget, 182s elapsed, input 58x the
 * fixture" tells a person which case they are in even inside a coarse bucket.
 */
export const TIMEOUT_EVIDENCE = [
${(raw.evidence?.timeout ?? []).map((f) => `  ${quote(f)},`).join("\n")}
] as const;

/** Outcomes that share an action, in rendering order. Empty groups are kept: a
 *  family with no runs is a fact, and dropping it makes the page change shape. */
export function groupByAction(
  counts: Partial<Record<ToolOutcome, number>>,
): { action: OutcomeAction; outcomes: { outcome: ToolOutcome; count: number }[]; total: number }[] {
  return ACTION_ORDER.map((action) => {
    const outcomes = (Object.keys(TOOL_OUTCOMES) as ToolOutcome[])
      .filter((outcome) => TOOL_OUTCOMES[outcome].action === action)
      .map((outcome) => ({ outcome, count: counts[outcome] ?? 0 }));
    return { action, outcomes, total: outcomes.reduce((sum, o) => sum + o.count, 0) };
  });
}
`;

await writeFile(OUT, file);
console.log(
  `outcomes.generated.ts: ${toolOutcomes.length} tool outcomes, ${agentOutcomes.length} agent outcomes, ${actions.length} actions`,
);
